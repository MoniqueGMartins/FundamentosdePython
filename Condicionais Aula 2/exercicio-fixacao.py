# Solicite a temperatura para o usuário. Se estiver abaixo de 16 graus, informa ao usuário para pegar uma blusa. Ao final escreva fim do programa

#Entrada
temperatura = int(input("Digite a temperatura atual: ")) 

#Processamento
if temperatura <= 16 :
    print("Pegue uma blusa pois está frio 🥶")
else :
    print("Pegue um óculos de sol 😎")

#Saída   
print("Fim do programa")

